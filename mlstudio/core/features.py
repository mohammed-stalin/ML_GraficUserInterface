"""Feature detection and leakage-free preprocessing shared by every model.

All imputation, scaling and encoding happen inside scikit-learn pipelines, so
statistics are learned from the training split only and re-applied to the test
split (the original app filled missing values on the full dataset before
splitting, which leaks test information into training).
"""
from __future__ import annotations

from dataclasses import dataclass, field

import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler

GENERATED_COLUMNS = ("Cluster",)


@dataclass
class FeatureSpec:
    numeric: list[str] = field(default_factory=list)
    categorical: list[str] = field(default_factory=list)
    dropped: dict[str, str] = field(default_factory=dict)

    @property
    def used(self) -> list[str]:
        return self.numeric + self.categorical


def infer_features(X: pd.DataFrame, include_categorical: bool = True) -> FeatureSpec:
    """Split columns into numeric / categorical and skip ones that cannot help a model."""
    spec = FeatureSpec()
    n_rows = len(X)
    for col in X.columns:
        series = X[col]
        n_unique = series.nunique(dropna=True)
        if col in GENERATED_COLUMNS:
            spec.dropped[col] = "generated by clustering"
        elif series.isna().all():
            spec.dropped[col] = "all values missing"
        elif n_unique <= 1:
            spec.dropped[col] = "constant value"
        elif pd.api.types.is_bool_dtype(series) or pd.api.types.is_numeric_dtype(series):
            if (pd.api.types.is_integer_dtype(series) and n_rows >= 20 and n_unique == n_rows
                    and series.is_monotonic_increasing):
                spec.dropped[col] = "row identifier (unique, increasing)"
            else:
                spec.numeric.append(col)
        elif pd.api.types.is_datetime64_any_dtype(series):
            spec.dropped[col] = "datetime column (not supported)"
        elif n_rows >= 20 and n_unique > 0.9 * n_rows:
            spec.dropped[col] = "identifier-like text (unique per row)"
        elif not include_categorical:
            spec.dropped[col] = "categorical (excluded)"
        else:
            spec.categorical.append(col)
    if not spec.used:
        raise ValueError("No usable feature columns. Load more columns or include categorical features.")
    return spec


def prepare_frame(X: pd.DataFrame, spec: FeatureSpec) -> pd.DataFrame:
    """Return only the used columns with types the encoders accept."""
    out = X[spec.used].copy()
    for col in spec.numeric:
        if pd.api.types.is_bool_dtype(out[col]):
            out[col] = out[col].astype(float)
    for col in spec.categorical:
        out[col] = out[col].where(out[col].isna(), out[col].astype(str)).astype(object)
    return out


def build_preprocessor(spec: FeatureSpec, max_categories: int | None = 40,
                       sparse: bool = False) -> ColumnTransformer:
    """Impute + scale numeric columns, impute + one-hot encode categorical columns.

    ``max_categories`` groups rare categories into an "infrequent" bucket; ``None``
    keeps every category (use with ``sparse=True`` for high-cardinality columns).
    """
    encoder_kwargs = {"sparse_output": sparse}
    if max_categories:
        encoder_kwargs.update(handle_unknown="infrequent_if_exist", max_categories=max_categories)
    else:
        encoder_kwargs.update(handle_unknown="ignore")
    return ColumnTransformer(
        [
            ("num", make_pipeline(SimpleImputer(strategy="median"), StandardScaler()), spec.numeric),
            ("cat", make_pipeline(SimpleImputer(strategy="most_frequent"), OneHotEncoder(**encoder_kwargs)),
             spec.categorical),
        ],
        sparse_threshold=1.0 if sparse else 0,
        verbose_feature_names_out=False,
    )
